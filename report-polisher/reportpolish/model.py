"""Neutral document model shared by every stage of the pipeline."""
from dataclasses import dataclass, field


@dataclass
class Block:
    kind: str                  # heading | para | bullet | number | table | image | code
    text: str = ""             # inline markup: **bold**, *italic*, `code`
    level: int = 0             # heading level (1 = top)
    rows: list = field(default_factory=list)   # table rows (list of list of str)
    data: bytes = b""          # image bytes
    caption: str = ""          # table / figure caption (without the "Table 3" label)
    label: str = ""            # original "Table 3" / "Figure 2" number as written
    auto: bool = False         # generated by the tool, flag for human review


@dataclass
class Branding:
    company: str = ""
    logo: str = ""             # path to a PNG/JPG
    accent: str = "1F3864"     # hex, no '#'
    confidential: str = ""     # e.g. "Confidential - for internal use"


@dataclass
class Report:
    meta: dict = field(default_factory=dict)       # title, subtitle, author, date, ...
    blocks: list = field(default_factory=list)
    notes: list = field(default_factory=list)      # (severity, message) for the reviewer
